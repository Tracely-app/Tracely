/**
 * Dollars of daily budget, from the environment.
 *
 * An EMPTY value is "absent", not "0". Number("") is 0, and 0 means unlimited
 * here — so the obvious `TRACELY_DAILY_BUDGET_USD=` line in an .env.example
 * would have silently removed the ceiling. Only an explicit numeric 0 does
 * that, which is the documented way to turn it off.
 */
export function dailyBudgetUsd(env = process.env, variable = "TRACELY_DAILY_BUDGET_USD", fallback = SPEND.defaultDailyBudgetUsd) {
  const text = String(env[variable] ?? "").trim();
  if (!text) return fallback;
  const raw = Number(text);
  if (!Number.isFinite(raw) || raw < 0) return fallback;
  return raw;
}

/**
 * Rolling-window counter. stamp() BEFORE the call, not after — otherwise it
 * measures the gap between answers instead of between requests.
 */
export function rollingCounter(limit, windowMs = 3_600_000) {
  let times = [];
  return {
    ok() {
      const now = Date.now();
      times = times.filter((t) => now - t < windowMs);
      return times.length < limit;
    },
    stamp() {
      times.push(Date.now());
    },
    count() {
      const now = Date.now();
      times = times.filter((t) => now - t < windowMs);
      return times.length;
    },
  };
}

/**
 * Per-key rolling SUM: what each key added in the last `windowMs` — the
 * dollar twin of keyedRateLimiter, bounded the same way (oldest keys dropped
 * first; a dropped key starts again from nothing, which the pool on disk
 * still bounds). In memory on purpose, like the limiter: it smooths an hour.
 */
export function keyedRollingSum(windowMs = 3_600_000, maxKeys = SPEND.rateLimiterMaxKeys) {
  const byKey = new Map(); // key -> [[at, amount], ...]
  const live = (key, now) => {
    const list = (byKey.get(key) ?? []).filter(([at]) => now - at < windowMs);
    if (list.length) byKey.set(key, list);
    else byKey.delete(key);
    return list;
  };
  return {
    total(key, now = Date.now()) {
      return live(key, now).reduce((sum, [, amount]) => sum + amount, 0);
    },
    add(key, amount, now = Date.now()) {
      const n = Number(amount);
      if (!(n > 0) || !Number.isFinite(n)) return;
      const list = live(key, now);
      if (!byKey.has(key) && byKey.size >= maxKeys) {
        for (const k of byKey.keys()) {
          byKey.delete(k);
          if (byKey.size < maxKeys) break;
        }
      }
      list.push([now, n]);
      byKey.set(key, list);
    },
    size() {
      return byKey.size;
    },
  };
}

/**
 * Debounce-floor gate for live detection. The idle timer bounds nothing on its
 * own (type-pause-type clears it forever); the floor between calls is the
 * actual ceiling, stamped before the call.
 */
export function detectGate() {
  /* The desktop's rule (src/shared/liveDetect.ts shouldDetectNow), mirrored and
   * pinned by test/mirror-contracts.test.js. Two ways this copy used to differ:
   *  - it measured the RAW draft, so 79 characters and a few trailing spaces
   *    cleared the 80-character minimum here and not on the desktop;
   *  - it started from lastRunAt = 0, so "has never run" was only distinguished
   *    from "ran at the epoch" by the real clock being large. Null says it.
   * Both measure the trimmed draft now, and a first run skips the floor. */
  let lastRunAt = null;
  let lastText = null;
  return {
    shouldRun(raw, now = Date.now()) {
      const text = String(raw ?? "").trim();
      if (text.length < GUARDS.detect.minChars) return false;
      if (lastText !== null) {
        if (text === lastText) return false;
        if (Math.abs(text.length - lastText.length) < GUARDS.detect.minDelta) return false;
      }
      if (lastRunAt !== null && now - lastRunAt < GUARDS.detect.minIntervalMs) return false;
      return true;
    },
    stamp(raw, now = Date.now()) {
      lastRunAt = now; // before the call
      lastText = String(raw ?? "").trim();
    },
  };
}

/**
 * Per-key rolling rate limiter — one rollingCounter per caller, bounded.
 *
 * In memory on purpose: this bounds BURSTS, and a burst does not survive a
 * restart. The daily quotas are in SQLite because those must survive one.
 *
 * Eviction is oldest-first on insertion order rather than true LRU. A busy
 * caller can therefore be evicted and get a fresh allowance; that is
 * acceptable because this layer only smooths velocity — the daily quota and
 * the global budget are what actually bound spend.
 */
export function keyedRateLimiter(limit, windowMs = 60_000, maxKeys = SPEND.rateLimiterMaxKeys) {
  const byKey = new Map();
  return {
    ok(key) {
      const c = byKey.get(key);
      return c ? c.ok() : true;
    },
    stamp(key) {
      let c = byKey.get(key);
      if (!c) {
        if (byKey.size >= maxKeys) {
          for (const k of byKey.keys()) {
            byKey.delete(k);
            if (byKey.size < maxKeys) break;
          }
        }
        c = rollingCounter(limit, windowMs);
        byKey.set(key, c);
      }
      c.stamp();
    },
    size() {
      return byKey.size;
    },
  };
}
