/**
 * Cost guards — every automatic path needs a bound. Centralized so each one is
 * testable, and so nobody re-invents a cap inline. Two caps are not one cap:
 * per-analysis caps assume analyses are discrete units (they aren't, under
 * debounced live detection), so the rolling-window cap is the backstop.
 */

export const GUARDS = {
  maxInputChars: 30_000,          // how much text reaches any model call
  maxClaimsPerAnalysis: 40,       // how many claims one detection pass may produce
  maxAutoCritiqueClaims: 6,       // paid fact-checks per analysis, once per analysis id
  maxWebSearchesPerAnalysis: 4,   // paid searches per document analysis
  maxWebSearchesPerHour: 15,      // the backstop when "one analysis" stops meaning anything
  maxAutoSourcesPerCycle: 3,
  evidenceConcurrency: 3,         // claims searched at once in the sweep
  providerTimeoutMs: 6_000,       // a slow index returns empty, not late

  // Live-detect bounds ported from the production app's shared/liveDetect.ts,
  // which solved this already: 2.5s idle (past a comma, short of a reread),
  // a sentence-sized delta (fixing a typo and pausing must not re-read the
  // document), and a 15s floor — the idle timer alone bounds nothing, since
  // type-pause-type clears it forever.
  detect: {
    idleMs: 2500,                 // typing pause before detection may fire
    minChars: 80,                 // minimum draft length
    minDelta: 80,                 // minimum change since last run — sentence-sized
    minIntervalMs: 15_000,        // the hard floor between calls — the real ceiling
  },
};

/**
 * The spend cap's constants.
 *
 * WHY A GLOBAL BUDGET IS THE LOAD-BEARING LAYER, and everything else is
 * politeness:
 *
 * The extension deliberately needs no sign-in, so on a hosted server the
 * DEFAULT caller is anonymous. Anonymous has no identity we control:
 *   - an install id is generated by the client, so it can be rotated freely;
 *   - the client ADDRESS cannot be used for a daily cap at all, because
 *     Tracely's actual market is schools, and a few hundred real students
 *     behind one CGNAT or campus address are indistinguishable from one
 *     attacker behind that same address. A per-address daily quota generous
 *     enough for a school is useless against abuse, and one tight enough for
 *     abuse locks out the school. That option is rejected, not overlooked.
 *
 * So per-caller quotas bound ACCIDENTS and casual overuse, which is most of
 * the real risk, and the global budget is the only thing that bounds a
 * determined attacker. Set DAILY_BUDGET_USD to what you can afford to lose in
 * a day, because that is exactly what it is.
 *
 * Costs on the current fast tier (gpt-5.6-luna, effort medium on /api/check),
 * from the model eval, eval/models/FINDINGS.md, 2026-09-21, measured to cold:
 * a typing-pause check is 0.039-0.104 cents (1 sentence warm to 3 cold;
 * 0.0565-0.086 on an even mix of the two) and a 40-sentence first check
 * 0.34-0.39 cents; a source search is >= 1 cent because OpenAI bills
 * web_search per call ($10/1000) on top of tokens — about 10-25 typing-pause
 * checks. That ratio is why sources are shed first when the budget runs low.
 * (The 2026-09-21 smoke run measured luna source searches at 1.2-1.35 cents,
 * one search each.)
 */
